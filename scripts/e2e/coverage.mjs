#!/usr/bin/env node
/**
 * Builds user-testing/coverage-matrix.md: which persona touched which element of the app.
 * Input: user-testing/personas/<persona>/<project>-hits.json (written by the persona runs) and
 * e2e/personas/inventory.mjs. Exits non-zero when --strict is passed and an element is untouched.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BEHAVIORS, INVENTORY, OUT_OF_SCOPE } from "../../e2e/personas/inventory.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const dir = join(root, "user-testing", "personas");
const strict = process.argv.includes("--strict");

const runs = [];
for (const persona of readdirSync(dir).sort()) {
  for (const file of readdirSync(join(dir, persona)).filter((f) => f.endsWith("-hits.json"))) {
    const project = file.replace("-hits.json", "");
    const notes = join(dir, persona, `${project}-notes.json`);
    const meta = existsSync(notes) ? JSON.parse(readFileSync(notes, "utf8")) : {};
    runs.push({ persona, project, name: meta.persona ?? persona, behavior: meta.behavior ?? "", hits: JSON.parse(readFileSync(join(dir, persona, file), "utf8")) });
  }
}

const short = (p) => p.replace(/^\d+-/, "");
const covers = new Map(INVENTORY.map((e) => [e.id, new Map()]));
const matched = new Set();
for (const run of runs) {
  for (const hit of run.hits) {
    for (const e of INVENTORY) {
      if (e.match.test(hit)) {
        matched.add(hit);
        const by = covers.get(e.id);
        by.set(run.persona, (by.get(run.persona) ?? new Set()).add(run.project.includes("mobile") ? "iPhone" : "desktop"));
      }
    }
  }
}
const unclassified = [...new Set(runs.flatMap((r) => r.hits))].filter((h) => !matched.has(h) && !/^key\|(Enter|Tab)\|/.test(h)).sort();

const lines = [];
const personas = [...new Set(runs.map((r) => r.persona))].sort();
const covered = INVENTORY.filter((e) => covers.get(e.id).size > 0);
const uncovered = INVENTORY.filter((e) => covers.get(e.id).size === 0);
lines.push("# Coverage matrix", "");
lines.push(`${covered.length} of ${INVENTORY.length} interactive elements were used by at least one persona across ${personas.length} personas and ${runs.length} runs (desktop Chromium and iPhone WebKit). Generated by \`node scripts/e2e/coverage.mjs\` from what the pages actually received (clicks, edits, keys, drags, swipes), not from what the scripts intended.`, "");
lines.push("A cell shows the persona and where it touched the element: D = desktop, P = iPhone.", "");

for (const [key, title] of Object.entries(BEHAVIORS)) {
  const items = INVENTORY.filter((e) => e.behavior === key);
  lines.push(`## ${title}`, "", "| Area | Element | Used by |", "| --- | --- | --- |");
  for (const e of items) {
    const by = covers.get(e.id);
    const who = [...by].map(([p, where]) => `${short(p)} ${[...where].map((w) => (w === "desktop" ? "D" : "P")).sort().join("")}`).join(", ");
    lines.push(`| ${e.area} | ${e.element} | ${who || "**not touched**"} |`);
  }
  lines.push("");
}

lines.push("## Not touched", "");
lines.push(uncovered.length ? uncovered.map((e) => `- ${e.area}: ${e.element}`).join("\n") : "Every listed element was used.", "");
lines.push("## Not in this build (not covered by personas)", "", ...OUT_OF_SCOPE.map((s) => `- ${s}`), "");
lines.push("## Persona index", "", "| Persona | Behavior | Variations | Runs |", "| --- | --- | --- | --- |");
const seen = new Set();
for (const r of runs) {
  if (seen.has(r.persona)) continue;
  seen.add(r.persona);
  const notes = join(dir, r.persona, `${r.project}-notes.json`);
  const meta = existsSync(notes) ? JSON.parse(readFileSync(notes, "utf8")) : {};
  lines.push(`| ${r.name} | ${BEHAVIORS[meta.behavior] ?? ""} | ${(meta.variations ?? []).join(", ") || "-"} | ${runs.filter((x) => x.persona === r.persona).map((x) => (x.project.includes("mobile") ? "iPhone" : "desktop")).join(" + ")} |`);
}
lines.push("");
if (unclassified.length) {
  lines.push("## Interactions the inventory does not list yet", "", "Seen by the recorder but not matched to an inventory entry (extend `e2e/personas/inventory.mjs` if any is a real control):", "", ...unclassified.slice(0, 60).map((h) => `- \`${h}\``), "");
}
writeFileSync(join(root, "user-testing", "coverage-matrix.md"), lines.join("\n"));
console.log(`${covered.length}/${INVENTORY.length} elements covered; ${uncovered.length} untouched; ${unclassified.length} unclassified interactions.`);
for (const e of uncovered) console.log(`  untouched: ${e.area}: ${e.element}`);
if (strict && uncovered.length) process.exit(1);
